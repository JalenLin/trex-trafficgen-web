#!/bin/bash
# Install the TRex GUI backend on a TRex host from an offline bundle.
# Run from the extracted bundle directory. No sudo or internet needed for the
# default (per-user) install. See docs/deployment.md.
set -euo pipefail

usage() {
    cat <<EOF
Usage: ./install.sh [options]
  --prefix DIR       install location (default: ~/trex-gui)
  --trex-dir DIR     TRex install dir (default: the running TRex, else newest /opt/trex/v*)
  --trex-cfg FILE    TRex config used to pick the CPU (default: /etc/trex_cfg.yaml)
  --listen ADDR      address to listen on (default: 127.0.0.1; 0.0.0.0 = whole network,
                     no login yet). Only used when config.yaml is first written.
  --system           install a system-wide service (run with sudo); default is a user service
  --no-service       only install files, do not install or start a service
EOF
}

BUNDLE=$(cd "$(dirname "$0")" && pwd)
PREFIX=$HOME/trex-gui
TREX_DIR=""
TREX_CFG=/etc/trex_cfg.yaml
LISTEN=127.0.0.1
MODE=user

while [ $# -gt 0 ]; do
    case $1 in
        --prefix) PREFIX=$2; shift 2 ;;
        --trex-dir) TREX_DIR=$2; shift 2 ;;
        --trex-cfg) TREX_CFG=$2; shift 2 ;;
        --listen) LISTEN=$2; shift 2 ;;
        --system) MODE=system; shift ;;
        --no-service) MODE=none; shift ;;
        -h|--help) usage; exit 0 ;;
        *) usage; exit 1 ;;
    esac
done

if [ "$MODE" = system ]; then
    [ "$(id -u)" = 0 ] || { echo "--system needs root (use sudo)"; exit 1; }
    RUN_USER=${SUDO_USER:?run --system through sudo from the account that should own the service}
    [ "$PREFIX" = "$HOME/trex-gui" ] && PREFIX=$(getent passwd "$RUN_USER" | cut -d: -f6)/trex-gui
else
    RUN_USER=$(id -un)
fi

want=$(cat "$BUNDLE/PYTHON_VERSION")
have=$(python3 -c 'import sys; print("%d.%d" % sys.version_info[:2])')
[ "$want" = "$have" ] || { echo "this bundle is for python $want but python3 is $have; rebuild with deploy/make-bundle.sh $have"; exit 1; }

echo "==> installing $(cat "$BUNDLE/VERSION") to $PREFIX"
mkdir -p "$PREFIX"
rm -rf "$PREFIX/backend" "$PREFIX/frontend" "$PREFIX/.venv"
cp -r "$BUNDLE/backend" "$BUNDLE/frontend" "$PREFIX/"
cp "$BUNDLE/config.example.yaml" "$PREFIX/"
mkdir -p "$PREFIX/docs" && cp "$BUNDLE/docs/"* "$PREFIX/docs/"

echo "==> creating virtualenv (offline)"
# --without-pip: many hosts lack the python3-venv package (ensurepip); the
# bundled pip wheel is run directly instead.
python3 -m venv --without-pip "$PREFIX/.venv"
"$PREFIX/.venv/bin/python" "$(ls "$BUNDLE"/wheels/pip-*.whl)/pip" install -q --no-index \
    --find-links "$BUNDLE/wheels" -r "$BUNDLE/requirements.txt"

if [ -z "$TREX_DIR" ]; then
    running=$(pgrep -a -f "[t]-rex-64 " | grep -o '/[^ ]*/t-rex-64' | head -1 || true)
    if [ -n "$running" ]; then
        TREX_DIR=$(dirname "$running")
    else
        TREX_DIR=$(ls -d /opt/trex/v* 2>/dev/null | grep -v '\.tar' | sort -V | tail -1 || true)
    fi
fi

if [ -f "$PREFIX/config.yaml" ]; then
    echo "==> keeping existing $PREFIX/config.yaml"
else
    echo "==> writing $PREFIX/config.yaml"
    "$PREFIX/.venv/bin/python" - "$PREFIX/config.yaml" "$TREX_DIR" "$TREX_CFG" "$LISTEN" <<'EOF'
import os, sys, yaml

out, trex_dir, trex_cfg, listen = sys.argv[1:]
client = os.path.join(trex_dir, "automation/trex_control_plane/interactive") if trex_dir else ""
if not (client and os.path.isdir(os.path.join(client, "trex"))):
    sys.exit(f"TRex client not found under {trex_dir!r}; rerun with --trex-dir")

master = 0
busy = set()
try:
    platform = (yaml.safe_load(open(trex_cfg)) or [{}])[0].get("platform", {})
    master = platform.get("master_thread_id", 0)
    busy = {platform.get("latency_thread_id")} | {t for d in platform.get("dual_if", []) for t in d.get("threads", [])}
    print(f"    {trex_cfg}: master_thread_id={master}")
except FileNotFoundError:
    print(f"    WARNING: {trex_cfg} not found; assuming TRex master runs on CPU 0. Check docs/deployment.md.")
if master in busy:
    print(f"    WARNING: CPU {master} is also a TRex latency/data-plane thread; choose another CPU by hand.")

config = {
    "server": {"host": listen, "port": 8080, "stats_interval": 1.0, "cpu_affinity": [master]},
    "hosts": [{
        "id": "local",
        "name": f"{os.uname().nodename} ({os.path.basename(trex_dir.rstrip('/'))})",
        "server": "127.0.0.1",
        "client_path": client,
    }],
}
with open(out, "w") as f:
    f.write("# Generated by install.sh. See docs/deployment.md before changing cpu_affinity.\n")
    yaml.safe_dump(config, f, sort_keys=False, allow_unicode=True)
print(f"    TRex client: {client}")
print(f"    cpu_affinity: [{master}]")
print(f"    listen: {listen}:8080")
EOF
fi
if [ "$MODE" = system ]; then chown -R "$RUN_USER": "$PREFIX"; fi

install_unit() {  # $1 = unit path, $2 = WantedBy, $3 = User= line
    sed -e "s|@PREFIX@|$PREFIX|g" -e "s|@WANTED_BY@|$2|" -e "s|@USER_LINE@|$3|" \
        "$BUNDLE/trex-gui.service.in" > "$1"
}

case $MODE in
    user)
        mkdir -p ~/.config/systemd/user
        install_unit ~/.config/systemd/user/trex-gui.service default.target ""
        systemctl --user daemon-reload
        systemctl --user enable trex-gui.service
        systemctl --user restart trex-gui.service   # restart, not just start: an upgrade must replace the running code
        echo "==> started user service: systemctl --user status trex-gui"
        if [ "$(loginctl show-user "$RUN_USER" -p Linger --value 2>/dev/null)" != yes ]; then
            echo "    NOTE: user services stop when $RUN_USER logs out and do not start at boot."
            echo "          To keep it running: sudo loginctl enable-linger $RUN_USER"
        fi
        ;;
    system)
        install_unit /etc/systemd/system/trex-gui.service multi-user.target "User=$RUN_USER"
        systemctl daemon-reload
        systemctl enable trex-gui.service
        systemctl restart trex-gui.service
        echo "==> started system service: systemctl status trex-gui"
        ;;
    none)
        echo "==> files installed; start by hand with:"
        echo "    cd $PREFIX/backend && ../.venv/bin/python -m trex_gui -c ../config.yaml"
        ;;
esac

echo "==> verify the CPU pinning: see 'Verify' in $PREFIX/docs/deployment.md"
